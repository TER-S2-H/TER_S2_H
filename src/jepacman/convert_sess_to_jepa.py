#!/usr/bin/env python3
"""
Convert Pac-Man session pickles to JEPA-compatible per-agent observation format.

This script is a post-processor for sessions generated by the Pac-Man simulator.
It does NOT modify the original session files — it produces new .pkl files in the
output directory with the following structure:

  List[  # one entry per frame (last frame excluded — no next action to infer)
    List[  # one entry per agent: [pacman, ghost_1, ghost_2, ghost_3, ghost_4]
      {
        "visible_cells": List[CellDict],  # always length MAX_VISIBLE_CELLS (padded)
        "action":        int,             # 0=up, 1=down, 2=left, 3=right, -1=stayed
        "agent_type":    str,             # "pacman" or "ghost"
        "agent_id":      int,             # 0=pacman, 1-4=ghosts
      }
    ]
  ]

CellDict keys (case_dim = 8 features; dx/dy are positions, not features):
  dx, dy                     — relative offset from agent (dy>0 = up, dy<0 = down)
  wall_north/south/east/west — bool  (4 features)
  has_pellet                 — bool  ┐
  has_super_pellet           — bool  │ 4 content features
  has_ghost                  — bool  │ (NOT one-hot; kept separate for flexibility)
  has_pacman                 — bool  ┘
  is_pad                     — bool  True for padding cells (all other fields are 0/False)

Visibility rule: line-of-sight in 4 cardinal directions until the first wall,
using the graph adjacency from the session. Own cell is always included.
Tunnels (wrap-around edges) are transparent to vision.
Padding: visible_cells is always padded to MAX_VISIBLE_CELLS=81 with PAD_CELL.

Dataset usage:
  Use PacManJEPADataset to iterate over sliding windows of T+j consecutive frames
  across all converted session files.
"""

import argparse
import os
import pickle
from typing import Dict, List, Set, Tuple

Coord = Tuple[int, int]

# Maximum number of visible cells per agent observation (padded to this length).
# Upper bound: a 28-col × 31-row maze has at most 27+30 = 57 corridor cells + own
# cell = 58 in a fully open cross. 81 gives a safe margin for any maze variant.
MAX_VISIBLE_CELLS: int = 81

# Number of features per cell used by the model (update Config accordingly).
# Breakdown:
#   wall_north + wall_south + wall_east + wall_west  →  4
#   has_pellet + has_super_pellet + has_ghost + has_pacman  →  4
#   total  →  8   (dx/dy are positional encodings, NOT part of case_dim)
CASE_DIM: int = 8

# Sentinel dict used to right-pad visible_cells to MAX_VISIBLE_CELLS.
# is_pad=True lets the model mask out these entries in attention.
PAD_CELL: dict = {
    "dx": 0, "dy": 0,
    "wall_north": False, "wall_south": False,
    "wall_east":  False, "wall_west":  False,
    "has_pellet":       False,
    "has_super_pellet": False,
    "has_ghost":        False,
    "has_pacman":       False,
    "is_pad":           True,
}


# ---------------------------------------------------------------------------
# Graph helpers
# ---------------------------------------------------------------------------

def build_coord_adjacency(session: dict) -> Dict[Coord, Set[Coord]]:
    """
    Rebuild a coord → set-of-neighbor-coords adjacency map
    from the COO graph stored in the session.
    """
    index_to_coord: Dict[int, list] = session["graph"]["index_to_coord"]
    coo_src: List[int] = session["graph"]["coo_src"]
    coo_dst: List[int] = session["graph"]["coo_dst"]

    adjacency: Dict[Coord, Set[Coord]] = {}
    for src_idx, dst_idx in zip(coo_src, coo_dst):
        src = tuple(index_to_coord[src_idx])
        dst = tuple(index_to_coord[dst_idx])
        adjacency.setdefault(src, set()).add(dst)

    return adjacency


# ---------------------------------------------------------------------------
# Visibility
# ---------------------------------------------------------------------------

def compute_visible_coords(
    agent_coord: Coord,
    adjacency: Dict[Coord, Set[Coord]],
) -> List[Coord]:
    """
    Return all coords visible from agent_coord (line-of-sight, 4 directions).
    Vision stops at the first missing edge (wall). Own cell is always included.
    Tunnel edges are handled transparently because they appear in the adjacency.

    If agent_coord is not in the adjacency (e.g. ghost still in the house on a
    PATHBLANK node with no outgoing edges), only the agent's own cell is returned.
    """
    visible: List[Coord] = [agent_coord]

    for delta_x, delta_y in ((0, -1), (0, 1), (-1, 0), (1, 0)):
        cx, cy = agent_coord
        while True:
            nx, ny = cx + delta_x, cy + delta_y
            neighbors = adjacency.get((cx, cy), set())
            if (nx, ny) not in neighbors:
                break
            visible.append((nx, ny))
            cx, cy = nx, ny

    return visible


# ---------------------------------------------------------------------------
# Wall flags
# ---------------------------------------------------------------------------

def get_wall_flags(coord: Coord, adjacency: Dict[Coord, Set[Coord]]) -> dict:
    """
    Return wall booleans for the 4 cardinal directions of a cell.
    A wall exists if there is no edge to the adjacent cell.

    Convention (screen coordinates, y increases downward):
      north → (x, y-1)   south → (x, y+1)
      east  → (x+1, y)   west  → (x-1, y)
    """
    x, y = coord
    neighbors = adjacency.get(coord, set())
    return {
        "wall_north": (x, y - 1) not in neighbors,
        "wall_south": (x, y + 1) not in neighbors,
        "wall_east":  (x + 1, y) not in neighbors,
        "wall_west":  (x - 1, y) not in neighbors,
    }


# ---------------------------------------------------------------------------
# Action inference
# ---------------------------------------------------------------------------

def infer_action(cur: Coord, nxt: Coord) -> int:
    """
    Derive the discrete action from consecutive position coordinates.

    Screen-coordinate system (y increases downward):
      0 = up    (y decreases)
      1 = down  (y increases)
      2 = left  (x decreases)
      3 = right (x increases)
     -1 = stayed / indeterminate (blocked or last frame)
    """
    dx = nxt[0] - cur[0]
    dy = nxt[1] - cur[1]

    if dy < 0:
        return 0  # up
    if dy > 0:
        return 1  # down
    if dx < 0:
        return 2  # left
    if dx > 0:
        return 3  # right
    return -1


# ---------------------------------------------------------------------------
# Per-cell dict
# ---------------------------------------------------------------------------

def build_cell_dict(
    cell_coord: Coord,
    agent_coord: Coord,
    adjacency: Dict[Coord, Set[Coord]],
    active_pellets: Set[Coord],
    active_energizers: Set[Coord],
    ghost_coords: List[Coord],
    pacman_coord: Coord,
) -> dict:
    """
    Build the observation dict for a single visible cell.

    dx/dy are in a math-convention frame (dy>0 = up = north).
    """
    dx = cell_coord[0] - agent_coord[0]
    # Invert y so that dy>0 means "above" the agent (math / user convention).
    dy = agent_coord[1] - cell_coord[1]

    return {
        "dx": dx,
        "dy": dy,
        **get_wall_flags(cell_coord, adjacency),
        "has_pellet":       cell_coord in active_pellets,
        "has_super_pellet": cell_coord in active_energizers,
        "has_ghost":        cell_coord in ghost_coords,
        "has_pacman":       cell_coord == pacman_coord,
        "is_pad":           False,
    }


# ---------------------------------------------------------------------------
# Per-agent observation
# ---------------------------------------------------------------------------

def build_agent_obs(
    agent_coord: Coord,
    next_coord: Coord,
    agent_type: str,
    agent_id: int,
    adjacency: Dict[Coord, Set[Coord]],
    active_pellets: Set[Coord],
    active_energizers: Set[Coord],
    ghost_coords: List[Coord],
    pacman_coord: Coord,
) -> dict:
    visible_coords = compute_visible_coords(agent_coord, adjacency)

    visible_cells = [
        build_cell_dict(
            cell, agent_coord, adjacency,
            active_pellets, active_energizers, ghost_coords, pacman_coord,
        )
        for cell in visible_coords
    ]

    # Pad to MAX_VISIBLE_CELLS so every agent-obs has a fixed-length sequence.
    # The dataloader can use is_pad=True to build an attention mask.
    n_real = len(visible_cells)
    if n_real < MAX_VISIBLE_CELLS:
        visible_cells += [PAD_CELL] * (MAX_VISIBLE_CELLS - n_real)
    elif n_real > MAX_VISIBLE_CELLS:
        # Should never happen in a standard maze; truncate defensively.
        visible_cells = visible_cells[:MAX_VISIBLE_CELLS]

    return {
        "visible_cells": visible_cells,          # always length MAX_VISIBLE_CELLS
        "n_visible":     min(n_real, MAX_VISIBLE_CELLS),  # real cell count before padding
        "action":        infer_action(agent_coord, next_coord),
        "agent_type":    agent_type,
        "agent_id":      agent_id,
    }


# ---------------------------------------------------------------------------
# Session conversion
# ---------------------------------------------------------------------------

def convert_session(session: dict) -> List[List[dict]]:
    """
    Convert one session into a list of per-frame agent observations.

    The last frame is excluded because no action can be inferred from it.
    Each entry is a list of 5 agent dicts:
      index 0   → Pac-Man  (agent_id=0)
      index 1-4 → Ghosts   (agent_id=1..4)
    """
    adjacency = build_coord_adjacency(session)
    frames = session["frames"]
    converted: List[List[dict]] = []

    for t in range(len(frames) - 1):
        frame = frames[t]
        next_frame = frames[t + 1]

        pacman_coord: Coord = tuple(frame["pacman_pos"])
        next_pacman_coord: Coord = tuple(next_frame["pacman_pos"])
        ghost_coords: List[Coord] = [tuple(g) for g in frame["ghost_positions"]]
        next_ghost_coords: List[Coord] = [tuple(g) for g in next_frame["ghost_positions"]]

        # Use frozensets for O(1) membership tests.
        active_pellets: Set[Coord] = {tuple(p) for p in frame["active_pellets"]}
        active_energizers: Set[Coord] = {tuple(e) for e in frame["active_energizers"]}

        frame_obs: List[dict] = []

        # --- Pac-Man (agent_id=0) ---
        frame_obs.append(
            build_agent_obs(
                pacman_coord, next_pacman_coord,
                agent_type="pacman", agent_id=0,
                adjacency=adjacency,
                active_pellets=active_pellets,
                active_energizers=active_energizers,
                ghost_coords=ghost_coords,
                pacman_coord=pacman_coord,
            )
        )

        # --- Ghosts (agent_id=1..4) ---
        for i in range(4):
            frame_obs.append(
                build_agent_obs(
                    ghost_coords[i], next_ghost_coords[i],
                    agent_type="ghost", agent_id=i + 1,
                    adjacency=adjacency,
                    active_pellets=active_pellets,
                    active_energizers=active_energizers,
                    ghost_coords=ghost_coords,
                    pacman_coord=pacman_coord,
                )
            )

        converted.append(frame_obs)

    return converted


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Convert Pac-Man session pickles to JEPA per-agent observation format."
    )
    parser.add_argument(
        "input_dir",
        help="Directory containing session .pkl files (or a single seed subfolder).",
    )
    parser.add_argument(
        "-o", "--output-dir",
        default="./jepa_sessions",
        help="Output directory for converted .pkl files (default: ./jepa_sessions).",
    )
    parser.add_argument(
        "--recurse",
        action="store_true",
        help="Recursively search input_dir for .pkl files (useful for multi-seed directories).",
    )
    args = parser.parse_args()

    # Collect all .pkl paths.
    pkl_paths: List[str] = []
    if args.recurse:
        for root, _, files in os.walk(args.input_dir):
            for fname in sorted(files):
                if fname.endswith(".pkl"):
                    pkl_paths.append(os.path.join(root, fname))
    else:
        for fname in sorted(os.listdir(args.input_dir)):
            if fname.endswith(".pkl"):
                pkl_paths.append(os.path.join(args.input_dir, fname))

    if not pkl_paths:
        print(f"No .pkl files found in '{args.input_dir}'.")
        return

    print(f"Found {len(pkl_paths)} session file(s).")

    for pkl_path in pkl_paths:
        # Mirror the subdirectory structure under output_dir.
        rel_path = os.path.relpath(pkl_path, args.input_dir)
        out_path = os.path.join(args.output_dir, rel_path)
        os.makedirs(os.path.dirname(out_path), exist_ok=True)

        with open(pkl_path, "rb") as f:
            session = pickle.load(f)

        converted = convert_session(session)

        with open(out_path, "wb") as f:
            pickle.dump(converted, f)

        print(
            f"  {rel_path} → {len(converted)} frame(s), "
            f"{sum(len(obs) for obs in converted)} agent-obs total"
        )

    print(f"\nDone. Converted files saved to '{args.output_dir}'.")


if __name__ == "__main__":
    main()